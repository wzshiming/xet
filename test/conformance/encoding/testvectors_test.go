// triggeringData repeats triggeringPattern followed by padding zero bytes until
// at least n bytes are filled, as xet-core's get_triggering_base_data does.
func triggeringData(n, padding int) []byte {
	data := make([]byte, 0, max(n, len(triggeringPattern)+padding))
	data = append(data, triggeringPattern...)
	data = append(data, make([]byte, padding)...)
	for len(data) < n {
		data = append(data, data[:min(n-len(data), len(data))]...)
	}
	return data
}

