// splitMixData returns n bytes of a SplitMix64 stream written as little-endian
// 64-bit words, as xet-core's create_random_data produces them.
func splitMixData(n int, seed uint64) []byte {
	result := make([]byte, 0, n+8)
	state := seed
	for len(result) < n {
		state += 0x9E3779B97F4A7C15
		z := state
		z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
		z = (z ^ (z >> 27)) * 0x94D049BB133111EB
		result = binary.LittleEndian.AppendUint64(result, z^(z>>31))
	}
	return result[:n]
}

