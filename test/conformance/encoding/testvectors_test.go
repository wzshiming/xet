// maskTriggerTail is the first big-endian 3-byte counter after 61 zero bytes
// whose 64-byte-window gearhash satisfies xet.GearhashMask; the mask-hit cases
// pin it against the reference.
var maskTriggerTail = [3]byte{0x02, 0x31, 0xfb}

// maskHitTail is the number of zero bytes maskHitData appends after the hit.
const maskHitTail = 1000

// maskHitData returns cuts[last]+maskHitTail zero bytes, hitting the mask at
// each cut and nowhere else; cuts must be at least 64 bytes apart, and the
// chunker's size rules decide which hits become boundaries.
func maskHitData(cuts ...int) []byte {
	data := make([]byte, cuts[len(cuts)-1]+maskHitTail)
	for _, cut := range cuts {
		copy(data[cut-len(maskTriggerTail):cut], maskTriggerTail[:])
	}
	return data
}
